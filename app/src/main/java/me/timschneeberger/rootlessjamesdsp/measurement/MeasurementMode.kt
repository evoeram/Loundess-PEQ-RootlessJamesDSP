package me.timschneeberger.rootlessjamesdsp.measurement

/**
 * Режим измерения каналов.
 *
 * - [LEFT] — только левый канал
 * - [RIGHT] — только правый канал
 * - [LR_SEQUENTIAL] — последовательное измерение L затем R с расчётом
 *   межканальной задержки через два probe-сигнала.
 *   Композитный сигнал на стереовыходе:
 *     Левый:  [тишина 100мс][probe L 1кГц 100мс][тишина 300мс][sweep L 5с][тишина ...]
 *     Правый: [тишина ...                                  ][probe R 1кГц 100мс][тишина 300мс][sweep R 5с]
 *   Запись моно, детектируются оба probe → извлекаются L и R sweep отдельно.
 * - [BOTH] — одновременное измерение L+R (сигнал на оба канала одновременно).
 */
enum class MeasurementMode {
    LEFT,
    RIGHT,
    LR_SEQUENTIAL,
    BOTH
}
